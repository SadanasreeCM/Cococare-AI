def t(key: str, language: str = "en", **kwargs) -> str:
    """
    Get translated text for a key in the given language code.
    Falls back to English if key or language is missing.
    Supports formatting string kwargs like t("hello_user", lang, name="John").
    """
    lang_dict = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    text = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs and isinstance(text, str):
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
